    "조금", "가끔", "그냥", "대해", "대한", "관련", "관해", "정말", "너무", "매우",
    "아주", "많이", "가장", "제일", "함께", "같이", "서로", "모두", "전부", "다들",
    "그것", "이것", "저것", "무엇", "때문", "위해", "통해", "가지", "번째",
    "이번", "다음", "지난", "요즘", "평소", "항상", "자주", "때때", "약간",
    "상당", "훨씬", "특히", "물론", "다만", "하지", "되지", "있지", "없지",
